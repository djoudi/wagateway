      <section id="a3">
        <h2><span class="n">3</span> المحتوى المحظور</h2>
        <p>يُحظر استخدام المنصة لإرسال أو تسهيل إرسال أي محتوى من الفئات التالية، دون استثناء:</p>
        <ul>
          <li>محتوى يخالف التشريع الجزائري النافذ، بما في ذلك قوانين الإعلام والتحريض والآداب العامة.</li>
          <li>رسائل احتيالية أو تصيّد (Phishing) تنتحل هوية جهات أخرى للحصول على بيانات حساسة.</li>
          <li>روابط تحتوي على برمجيات خبيثة (Malware) أو تُستخدم لاختراق أجهزة المستلمين.</li>
          <li>مخططات مالية هرمية أو استثمارات وهمية أو عروض "ربح سريع" مضلِّلة.</li>
          <li>خطاب كراهية، تحريض على العنف، أو محتوى يستهدف الأفراد أو الجماعات بالإساءة.</li>
          <li>محتوى إباحي أو جنسي صريح، أو محتوى يستغل القُصَّر بأي شكل.</li>
          <li>انتحال هوية شخص أو جهة أو مؤسسة أخرى دون تفويض.</li>
          <li>حملات دعائية سياسية أو دينية جماعية غير مرغوب فيها.</li>
          <li>ادعاءات طبية أو صحية مضلِّلة، أو ترويج لأدوية أو علاجات غير مرخّصة.</li>
        </ul>
      </section>

      <section id="a4">
        <h2><span class="n">4</span> قواعد الإرسال الجماعي</h2>
        <p>عند استخدام ميزة الإرسال الجماعي (Bulk Send)، يجب:</p>
        <ul>
          <li>إرسال الرسائل فقط لقائمة أرقام حصلتَ على موافقتها المسبقة وفق القسم 2.</li>
          <li>إبقاء خيار "التأخير العشوائي" مفعّلاً — تعطيله مسؤوليتك الكاملة وقد يُعرِّض رقمك للحظر الفوري.</li>
          <li>احترام حدود الإرسال اليومية المرتبطة بخطتك دون محاولة الالتفاف عليها عبر حسابات متعددة.</li>
          <li>تضمين وسيلة واضحة لطلب التوقف عن الاستقبال (مثال: "أرسل 'توقف' لإلغاء الاشتراك") والاستجابة لها فوراً.</li>
          <li>عدم إعادة استخدام نفس القائمة لإرسال حملات متكررة خلال فترات زمنية قصيرة دون تفاعل حقيقي من المستلمين.</li>
        </ul>
      </section>

