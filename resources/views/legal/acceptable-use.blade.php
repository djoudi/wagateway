        <h2><span class="n">5</span> إساءة استخدام واجهة API</h2>
        <ul>
          <li>يُحظر محاولة تجاوز حدود معدل الطلبات (Rate Limits) المفروضة على مفاتيح API.</li>
          <li>يُحظر مشاركة مفاتيح API الخاصة بك مع أطراف غير مصرَّح لها، أو إعادة بيع الوصول للمنصة دون اتفاق تجاري رسمي معنا.</li>
          <li>يُحظر استخدام المنصة لبناء أدوات تُمكِّن أطرافاً ثالثة من إرسال رسائل غير مرغوب فيها (Spam-as-a-Service).</li>
          <li>يُحظر أي محاولة لاختراق المنصة أو اختبار ثغراتها الأمنية دون تنسيق مسبق معنا (راجع سياسة الإبلاغ المسؤول عن الثغرات).</li>
        </ul>
