        <h2><span class="n">2</span> دورنا: متحكم أم معالج فرعي؟</h2>
        <p>يميّز القانون 18-07 بين "المتحكم في المعالجة" (الجهة التي تحدّد غرض ووسائل المعالجة) و"المعالج الفرعي" (الجهة التي تعالج البيانات نيابة عن المتحكم وبتعليماته). دورنا يختلف حسب نوع البيانات:</p>
        <table>
          <tr><th>نوع البيانات</th><th>دورنا</th><th>التوضيح</th></tr>
          <tr>
            <td>بيانات حسابك (اسمك، بريدك، معلومات الفوترة)</td>
            <td><strong>متحكم في المعالجة</strong></td>
            <td>نحدّد نحن غرض ووسائل معالجة هذه البيانات لتشغيل الخدمة وفوترتها.</td>
          </tr>
