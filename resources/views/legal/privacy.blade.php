            <td>أنت "المتحكم" في هذه البيانات بصفتك صاحب العلاقة مع جهات اتصالك، ونحن نعالجها بتعليماتك فقط (نقل الرسائل عبر واتساب) دون استخدامها لأي غرض آخر.</td>
          </tr>
