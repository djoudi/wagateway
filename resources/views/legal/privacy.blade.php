      <section id="p10">
        <h2><span class="n">10</span> حقوقك القانونية</h2>
        <p>وفقاً للقانون 18-07 المعدَّل، يحق لك:</p>
        <ul>
          <li><strong>حق الإعلام:</strong> معرفة كيف تُعالَج بياناتك (هذه الوثيقة تحقق هذا الحق).</li>
          <li><strong>حق الوصول:</strong> طلب نسخة من بياناتك الشخصية التي نحتفظ بها.</li>
          <li><strong>حق التصحيح:</strong> تصحيح أي بيانات غير دقيقة أو ناقصة.</li>
          <li><strong>حق الحذف:</strong> طلب حذف بياناتك، ضمن الحدود التي يفرضها الاحتفاظ القانوني الإلزامي (كالسجلات المحاسبية).</li>
          <li><strong>حق الاعتراض:</strong> الاعتراض على معالجة بياناتك لأغراض معيّنة كالتسويق المباشر.</li>
          <li><strong>حق سحب الموافقة:</strong> في أي وقت، دون التأثير على مشروعية المعالجة السابقة لسحبها.</li>
        </ul>
