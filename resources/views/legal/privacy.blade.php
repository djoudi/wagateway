      <section id="p5">
        <h2><span class="n">5</span> كيف نحمي بياناتك</h2>
        <p>نطبّق تدابير تقنية وتنظيمية حقيقية ومُفعَّلة فعلياً على مستوى البنية التحتية للمنصة، وليست مجرد التزام نظري:</p>
        <ul>
          <li><strong>مفاتيح API:</strong> لا تُخزَّن كنص صريح في قواعد بياناتنا مطلقاً — فقط بصمة تشفيرية (SHA-256) غير قابلة للعكس.</li>
          <li><strong>جلسات الأجهزة:</strong> بيانات جلسة كل رقم WhatsApp مشفّرة بخوارزمية AES-256 قبل التخزين.</li>
          <li><strong>الاتصال:</strong> جميع الاتصالات بين متصفحك والمنصة، وبين المنصة وأنظمتك عبر Webhooks، تمر عبر تشفير HTTPS.</li>
          <li><strong>توقيع الأحداث الصادرة:</strong> كل حدث Webhook مُوقَّع رقمياً (HMAC-SHA256) للتحقق من مصدره.</li>
          <li><strong>حماية من الاختراق:</strong> تقييد معدل محاولات الدخول، وسجل تدقيق أمني يرصد الأنماط المشبوهة تلقائياً.</li>
          <li><strong>الحذف الآمن:</strong> الأجهزة المحذوفة تُحفَظ مؤقتاً (Soft Delete) قبل الحذف النهائي، لمنع الحذف العرضي.</li>
        </ul>
      </section>

