      <section id="p7">
        <h2><span class="n">7</span> مع من نشارك بياناتك</h2>
        <p>لا نبيع بياناتك الشخصية لأي طرف ثالث. قد نشارك بيانات محدودة مع:</p>
        <ul>
          <li><strong>مزوّدي البنية التحتية</strong> (استضافة الخوادم، قواعد البيانات) الملزَمين تعاقدياً بحماية بياناتك.</li>
          <li><strong>مزوّدي خدمات الدفع</strong> عند معالجة اشتراكك، بالحد الأدنى اللازم لإتمام العملية.</li>
          <li><strong>السلطات المختصة</strong> عند وجود طلب قانوني ملزم وفق التشريع الجزائري.</li>
        </ul>
      </section>

